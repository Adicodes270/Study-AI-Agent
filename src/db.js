// Telegram ids can be larger than int32, so the columns are BIGINT.
// node-postgres returns BIGINT as a string by default; ids fit safely in a JS number.
pg.types.setTypeParser(20, (v) => Number(v));

let pool = null;
function getPool() {
  if (!DATABASE_URL) {
    throw new Error("DATABASE_URL is not set. Add your Neon connection string to .env");
  }
  if (!pool) {
    pool = new pg.Pool({
      connectionString: DATABASE_URL,
      max: 5, // keep small: Neon (and serverless) limit connections
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
    });
    // An idle client can be dropped by Neon (autosuspend); don't crash the process
    pool.on("error", (err) => console.log(`Postgres pool error: ${err.message}`));
  }
  return pool;
}

