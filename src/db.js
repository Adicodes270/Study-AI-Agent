// Runs once per process; concurrent callers share the same promise.
let schemaReady = null;

/** Create tables if they don't exist yet. Safe to call many times. */
export function initDb() {
  if (!hasDatabaseUrl()) {
    return Promise.resolve();
  }
  if (!schemaReady) {
    schemaReady = getPool()
      .query(SCHEMA)
      .then(() => undefined)
      .catch((err) => {
        schemaReady = null; // allow a retry on the next call
        throw err;
      });
  }
  return schemaReady;
}

/**
 * Run `fn(db)` inside a transaction. `db.query(sql, params)` is the usual
 * node-postgres client query (use $1, $2, ... placeholders; rows are in `.rows`).
 * Commits if everything worked, rolls back if anything threw.
 */
export async function withDb(fn) {
  await initDb();
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

/** Close the pool (for scripts and clean shutdown). */
export async function closeDb() {
  if (pool) {
    await pool.end();
    pool = null;
    schemaReady = null;
  }
}

// ---------------------------------------------------------------------------
// Granular Subject Migration Helper
// Automatically reorganizes any legacy "Social Science" chapters into History, Civics,
// Economics, or Geography, and any "Science" chapters into Physics, Chemistry, or Biology.
// ---------------------------------------------------------------------------
async function migrateUserChaptersToGranularSubjects(p, telegramUserId, chapters, results = []) {
  for (const c of chapters) {
    const granular = storedSubject(c.subject, c.title, c.pdf_url, "", c.number);
    if (granular && granular !== c.subject) {
      const oldSubj = c.subject;
      c.subject = granular;
      await p
        .query("UPDATE syllabus_chapters SET subject = $1 WHERE id = $2", [granular, c.id])
        .catch(() => {});
      await p
        .query(
          `UPDATE chapter_quiz_results
              SET subject = $1
            WHERE telegram_user_id = $2 AND subject = $3 AND exam = $4 AND chapter_title = $5`,
          [granular, telegramUserId, oldSubj, c.exam || "", c.title]
        )
        .catch(() => {});
      await p
        .query(
          `UPDATE chapter_resources
              SET subject = $1
            WHERE telegram_user_id = $2 AND subject = $3 AND exam = $4 AND chapter_title = $5`,
          [granular, telegramUserId, oldSubj, c.exam || "", c.title]
        )
        .catch(() => {});
    }
  }

  for (const r of results) {
    const granular = storedSubject(r.subject, r.chapter_title, "", "", null);
    if (granular && granular !== r.subject) {
      const oldSubj = r.subject;
      r.subject = granular;
      await p
        .query("UPDATE chapter_quiz_results SET subject = $1 WHERE id = $2", [granular, r.id])
        .catch(() => {});
      await p
        .query(
          `UPDATE chapter_resources
              SET subject = $1
            WHERE telegram_user_id = $2 AND subject = $3 AND exam = $4 AND chapter_title = $5`,
          [granular, telegramUserId, oldSubj, r.exam || "", r.chapter_title]
        )
        .catch(() => {});
    }
  }
}

