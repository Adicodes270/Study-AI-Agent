/**
 * Insert one or more spaced-repetition review rows into `review_schedule`.
 */
export async function insertReviews(userId, rows = []) {
  const inputRows = Array.isArray(userId)
    ? userId
    : Array.isArray(rows)
    ? rows
    : rows
    ? [rows]
    : [];
  const defaultUid = Array.isArray(userId) ? null : Number(userId);
  if (!inputRows.length) return [];

  const store = readLocalStore();
  store.reviewSchedule = Array.isArray(store.reviewSchedule) ? store.reviewSchedule : [];
  const inserted = [];

  for (const raw of inputRows) {
    if (!raw || typeof raw !== "object") continue;
    const uid = Number(raw.telegram_user_id ?? raw.telegramUserId ?? raw.userId ?? defaultUid);
    const subject = String(raw.subject || "General");
    const chapterTitle = String(raw.chapter_title ?? raw.chapterTitle ?? "");
    const subtopic = String(raw.subtopic || "");
    const intervalDays = Number(raw.interval_days ?? raw.intervalDays ?? 1) || 1;
    const dueRaw = raw.due_at ?? raw.dueAt;
    const dueAt = dueRaw
      ? new Date(dueRaw).toISOString()
      : new Date(Date.now() + intervalDays * 86_400_000).toISOString();
    const sourceQuizId =
      raw.source_quiz_id != null
        ? String(raw.source_quiz_id)
        : raw.sourceQuizId != null
        ? String(raw.sourceQuizId)
        : null;
    const status = String(raw.status || "pending");
    const createdAt =
      raw.created_at || raw.createdAt
        ? new Date(raw.created_at ?? raw.createdAt).toISOString()
        : new Date().toISOString();

    const localRow = {
      id: nextLocalRowId(store.reviewSchedule),
      telegram_user_id: uid,
      subject,
      chapter_title: chapterTitle,
      subtopic,
      due_at: dueAt,
      interval_days: intervalDays,
      source_quiz_id: sourceQuizId,
      status,
      created_at: createdAt,
    };
    store.reviewSchedule.push(localRow);

    if (hasDatabaseUrl()) {
      try {
        await initDb();
        const { rows: dbRows } = await getPool().query(
          `INSERT INTO review_schedule
             (telegram_user_id, subject, chapter_title, subtopic, due_at, interval_days, source_quiz_id, status, created_at)
           VALUES ($1, $2, $3, $4, $5::timestamptz, $6, $7, $8, $9::timestamptz)
           RETURNING id, telegram_user_id, subject, chapter_title, subtopic, due_at, interval_days, source_quiz_id, status, created_at`,
          [uid, subject, chapterTitle, subtopic, dueAt, intervalDays, sourceQuizId, status, createdAt]
        );
        if (dbRows[0]) {
          const formatted = formatReviewRow(dbRows[0]);
          localRow.id = formatted.id;
          localRow.created_at = formatted.created_at;
          inserted.push(formatted);
          continue;
        }
      } catch (e) {
        console.log(`Could not insert review into Postgres (saved locally): ${e.message}`);
      }
    }

    inserted.push(formatReviewRow(localRow));
  }

  writeLocalStore(store);
  return inserted;
}

/**
 * Return all `'pending'` reviews for `userId` with `due_at <= nowIso` (defaults to current time).
 */
export async function getDueReviews(userId, nowIso = new Date().toISOString()) {
  const cutoffIso = nowIso instanceof Date ? nowIso.toISOString() : new Date(nowIso).toISOString();
  const hasUserFilter = userId !== undefined && userId !== null;
  const uid = hasUserFilter ? Number(userId) : null;

  if (hasDatabaseUrl()) {
    try {
      await initDb();
      const { rows } = hasUserFilter
        ? await getPool().query(
            `SELECT id, telegram_user_id, subject, chapter_title, subtopic, due_at, interval_days, source_quiz_id, status, created_at
               FROM review_schedule
              WHERE telegram_user_id = $1
                AND status = 'pending'
                AND due_at <= $2::timestamptz
              ORDER BY due_at ASC, id ASC`,
            [uid, cutoffIso]
          )
        : await getPool().query(
            `SELECT id, telegram_user_id, subject, chapter_title, subtopic, due_at, interval_days, source_quiz_id, status, created_at
               FROM review_schedule
              WHERE status = 'pending'
                AND due_at <= $1::timestamptz
              ORDER BY due_at ASC, id ASC`,
            [cutoffIso]
          );
      return rows.map(formatReviewRow);
    } catch {}
  }

  const store = readLocalStore();
  const list = Array.isArray(store.reviewSchedule) ? store.reviewSchedule : [];
  const cutoffMs = new Date(cutoffIso).getTime();
  return list
    .filter(
      (r) =>
        (!hasUserFilter || Number(r.telegram_user_id) === uid) &&
        r.status === "pending" &&
        new Date(r.due_at).getTime() <= cutoffMs
    )
    .sort((a, b) => new Date(a.due_at).getTime() - new Date(b.due_at).getTime() || Number(a.id) - Number(b.id))
    .map(formatReviewRow);
}

/**
 * Update the status ('pending'|'sent'|'done'|'skipped') of a `review_schedule` row by `id`.
 */
