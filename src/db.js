// ---------------------------------------------------------------------------
// NotebookLM Resource Generation Persistence Helpers
// Resources are keyed by (telegram_user_id, subject, exam, chapter_title, resource_type)
// and strictly follow the No-Regeneration Rule (once generated, never overwritten).
// ---------------------------------------------------------------------------

/** Every syllabus chapter for this student, each with its map/list of generated resources. */
export async function getChaptersWithResources(telegramUserId) {
  await initDb();
  const p = getPool();
  const { rows: chapters } = await p.query(
    `SELECT sc.id, COALESCE(sc.class, ch.class) AS class, sc.subject, sc.exam, sc.number,
            sc.title, sc.note, sc.pdf_url, sc.match_status
       FROM syllabus_chapters sc
       LEFT JOIN chats ch ON ch.chat_id = sc.chat_id
      WHERE sc.chat_id = $1
      ORDER BY sc.subject, sc.exam, sc.number NULLS LAST, sc.id`,
    [telegramUserId]
  );
  await migrateUserChaptersToGranularSubjects(p, telegramUserId, chapters, []);

  const { rows: resources } = await p.query(
    `SELECT id, chapter_id, subject, exam, chapter_title, resource_type, title, summary,
            content_json, resource_url, created_at
       FROM chapter_resources
      WHERE telegram_user_id = $1
      ORDER BY created_at ASC`,
    [telegramUserId]
  );

  const byChapterKey = new Map();
  for (const r of resources) {
    const k = JSON.stringify(chapterKey(r));
    if (!byChapterKey.has(k)) byChapterKey.set(k, {});
    let parsedContent = null;
    try {
      parsedContent = r.content_json ? JSON.parse(r.content_json) : null;
    } catch {}
    byChapterKey.get(k)[r.resource_type] = {
      id: r.id,
      resource_type: r.resource_type,
      title: r.title,
      summary: r.summary,
      content: parsedContent,
      resource_url: r.resource_url || null,
      created_at: r.created_at,
    };
  }

  return chapters.map((c) => ({
    ...c,
    generated_resources: byChapterKey.get(JSON.stringify(chapterKey(c))) || {},
  }));
}

