import fs from "node:fs";
import path from "node:path";
import pg from "pg";

import { DATABASE_URL, ROOT } from "./config.js";

// Telegram ids can be larger than int32, so the columns are BIGINT.
// node-postgres returns BIGINT as a string by default; ids fit safely in a JS number.
pg.types.setTypeParser(20, (v) => Number(v));

// Local JSON fallback store when DATABASE_URL is not configured or temporarily unreachable
const LOCAL_STORE_PATH = path.join(ROOT, "data", "local_store.json");

function defaultLocalStore() {
  return {
    users: {},
    syllabi: {},
    quizResults: {},
    studyPlans: {},
    pomodoroSessions: {},
    focusLogs: [],
    morningBriefs: {},
    agentActions: [],
    agentMemory: {},
    reviewSchedule: [],
    pendingFollowups: [],
  };
}

export function readLocalStore() {
  try {
    if (fs.existsSync(LOCAL_STORE_PATH)) {
      const parsed = JSON.parse(fs.readFileSync(LOCAL_STORE_PATH, "utf8"));
      return {
        ...defaultLocalStore(),
        ...(parsed && typeof parsed === "object" ? parsed : {}),
      };
    }
  } catch {}
  return defaultLocalStore();
}

export function writeLocalStore(data) {
  try {
    fs.mkdirSync(path.dirname(LOCAL_STORE_PATH), { recursive: true });
    fs.writeFileSync(LOCAL_STORE_PATH, JSON.stringify(data, null, 2), "utf8");
  } catch {}
}

function currentDatabaseUrl() {
  return DATABASE_URL || (process.env.DATABASE_URL ?? "").trim();
}

let pool = null;
function getPool() {
  const connStr = currentDatabaseUrl();
  if (!connStr) {
    throw new Error("DATABASE_URL is not set. Add your Neon connection string to .env");
  }
  if (!pool) {
    pool = new pg.Pool({
      connectionString: connStr,
      max: 5, // keep small: Neon (and serverless) limit connections
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
    });
    // An idle client can be dropped by Neon (autosuspend); don't crash the process
    pool.on("error", (err) => console.log(`Postgres pool error: ${err.message}`));
  }
  return pool;
}

export function hasDatabaseUrl() {
  return Boolean(currentDatabaseUrl());
}

