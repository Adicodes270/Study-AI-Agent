// Quiz helpers. A student's syllabus lives under chat_id; in a private chat with the bot the
// chat id equals the Telegram user id, which is what the web app knows.
// ---------------------------------------------------------------------------

const chapterKey = (r) => [
  storedSubject(r.subject, r.title ?? r.chapter_title, r.pdf_url || "", "", r.number),
  r.exam || "",
  String(r.title ?? r.chapter_title ?? "").toLowerCase().trim(),
];

/** Every syllabus chapter for this student, each with its latest quiz result (including review) and any Pending quiz session. */
function getLocalSyllabusFallback(telegramUserId) {
  const store = readLocalStore();
  const direct = store.syllabi?.[String(telegramUserId)];
  if (Array.isArray(direct) && direct.length) return direct;
  for (const list of Object.values(store.syllabi || {})) {
    if (Array.isArray(list) && list.length) return list;
  }
  return [];
}

export async function getChaptersWithResults(telegramUserId) {
  if (!DATABASE_URL) {
    return getLocalSyllabusFallback(telegramUserId);
  }
  try {
    await initDb();
  } catch {
    return getLocalSyllabusFallback(telegramUserId);
  }
  const p = getPool();
  let { rows: chapters } = await p.query(
    `SELECT sc.id, COALESCE(sc.class, u.class_level) AS class, sc.subject, sc.exam, sc.number, sc.title, sc.note,
            sc.pdf_url, sc.match_status, sc.recommended_questions
       FROM syllabus_chapters sc
       LEFT JOIN users u ON u.telegram_user_id = sc.chat_id
      WHERE sc.chat_id = $1
      ORDER BY sc.subject, sc.exam, sc.number NULLS LAST, sc.id`,
    [telegramUserId]
  ).catch(() => ({ rows: [] }));

  if (!chapters.length) {
    const fallbackChat = await p.query(
      `SELECT chat_id FROM syllabus_chapters GROUP BY chat_id ORDER BY MAX(id) DESC LIMIT 1`
    ).catch(() => ({ rows: [] }));
    if (fallbackChat.rows[0]?.chat_id) {
      const fbRes = await p.query(
        `SELECT id, class, subject, exam, number, title, note, pdf_url, match_status, recommended_questions
           FROM syllabus_chapters
          WHERE chat_id = $1
          ORDER BY subject, exam, number NULLS LAST, id`,
        [fallbackChat.rows[0].chat_id]
      ).catch(() => ({ rows: [] }));
      chapters = fbRes.rows || [];
    }
  }
  if (!chapters.length) {
    const localList = getLocalSyllabusFallback(telegramUserId);
    if (localList.length) return localList;
  }
  const { rows: results } = await p.query(
    `SELECT id, subject, exam, chapter_title, score, total, percentage, revision_tier,
            revision_message, weak_subtopics_json, review_json, attempts, updated_at
       FROM chapter_quiz_results WHERE telegram_user_id = $1
       ORDER BY updated_at DESC`,
    [telegramUserId]
  );

  // Retroactively split any "Social Science" or "Science" chapters into History/Civics/Geography/Economics & Physics/Chemistry/Biology
  await migrateUserChaptersToGranularSubjects(p, telegramUserId, chapters, results);

  // Load ALL active, unsubmitted quiz sessions for this user (every unsubmitted session is pending)
  const { rows: pendingRows } = await p
    .query(
      `SELECT id, chapter_json, questions_json, answers_json, current_index, is_pending, updated_at
         FROM quiz_sessions
        WHERE telegram_user_id = $1
        ORDER BY updated_at DESC`,
      [telegramUserId]
    )
    .catch(() => ({ rows: [] }));

  const pendingByKey = new Map();
  const pendingById = new Map();
  const pendingByTitle = new Map();

  for (const row of pendingRows) {
    try {
      const ch = JSON.parse(row.chapter_json || "{}");
      const questions = JSON.parse(row.questions_json || "[]");
      const answers = JSON.parse(row.answers_json || "[]");
      if (!ch?.title || !Array.isArray(questions) || !questions.length) continue;
      const k = JSON.stringify(chapterKey(ch));
      const normalizedAnswers = questions.map((_, idx) =>
        typeof answers[idx] === "string" ? answers[idx] : ""
      );
      const answeredCount = normalizedAnswers.filter((a) => a.trim().length > 0).length;
      const pendingObj = {
        quizId: row.id,
        currentIndex: Math.max(0, Math.min(questions.length - 1, Number(row.current_index) || 0)),
        answers: normalizedAnswers,
        answeredCount,
        totalQuestions: questions.length,
        questions: questions.map(({ subtopic, question }) => ({ subtopic, question })),
        updatedAt: row.updated_at,
      };

      if (!pendingByKey.has(k)) pendingByKey.set(k, pendingObj);
      if (ch.id != null && !pendingById.has(String(ch.id))) pendingById.set(String(ch.id), pendingObj);
      const cleanTitle = String(ch.title).toLowerCase().trim();
      if (!pendingByTitle.has(cleanTitle)) pendingByTitle.set(cleanTitle, pendingObj);
    } catch {}
  }

  const byKey = new Map(results.map((r) => [JSON.stringify(chapterKey(r)), r]));
  const matchedKeys = new Set();

  const syllabusList = chapters.map((c) => {
    const k = JSON.stringify(chapterKey(c));
    matchedKeys.add(k);
    const r = byKey.get(k);
    const cleanTitle = String(c.title).toLowerCase().trim();
    const pendingQuiz =
      (c.id != null ? pendingById.get(String(c.id)) : null) ||
      pendingByKey.get(k) ||
      pendingByTitle.get(cleanTitle) ||
      null;

    let weak = [];
    let review = [];
    try { weak = r ? JSON.parse(r.weak_subtopics_json) : []; } catch {}
    try { review = r && r.review_json ? JSON.parse(r.review_json) : []; } catch {}
    return {
      ...c,
      pending_quiz: pendingQuiz,
      result: r
        ? {
            score: r.score,
            total: r.total,
            percentage: r.percentage,
            revision_tier: r.revision_tier,
            revision_message: r.revision_message,
            weak_subtopics: weak,
            review: Array.isArray(review) ? review : [],
            attempts: r.attempts,
            updated_at: r.updated_at,
          }
        : null,
    };
  });

  // Include any Custom Source quizzes the student created & completed
  for (const r of results) {
    const k = JSON.stringify(chapterKey(r));
    if (matchedKeys.has(k)) continue;
    let weak = [];
    let review = [];
    try { weak = JSON.parse(r.weak_subtopics_json); } catch {}
    try { review = r.review_json ? JSON.parse(r.review_json) : []; } catch {}
    const cleanTitle = String(r.chapter_title).toLowerCase().trim();
    const pendingQuiz = pendingByKey.get(k) || pendingByTitle.get(cleanTitle) || null;
    syllabusList.push({
      id: `custom-${r.id}`,
      class: null,
      subject: r.subject || "Custom Quizzes",
      exam: r.exam || "Custom Source",
      number: null,
      title: r.chapter_title,
      note: "Custom Source Quiz",
      pdf_url: null,
      match_status: "custom",
      is_custom: true,
      pending_quiz: pendingQuiz,
      result: {
        score: r.score,
        total: r.total,
        percentage: r.percentage,
        revision_tier: r.revision_tier,
        revision_message: r.revision_message,
        weak_subtopics: weak,
        review: Array.isArray(review) ? review : [],
        attempts: r.attempts,
        updated_at: r.updated_at,
      },
    });
  }

  return syllabusList;
}

/** One chapter, only if it belongs to this student (null otherwise). */
export async function getChapterForUser(telegramUserId, chapterId) {
  await initDb();
  const p = getPool();
  const { rows } = await p.query(
    `SELECT sc.id, COALESCE(sc.class, ch.class, u.class_level) AS class, sc.subject, sc.exam, sc.number,
            sc.title, sc.note, sc.pdf_url, sc.ncert_id, sc.match_status, sc.recommended_questions
       FROM syllabus_chapters sc LEFT JOIN chats ch ON ch.chat_id = sc.chat_id
       LEFT JOIN users u ON u.telegram_user_id = sc.chat_id
      WHERE sc.id = $1 AND sc.chat_id = $2`,
    [chapterId, telegramUserId]
  );
  const row = rows[0] || null;
  if (!row) return null;
  const granular = storedSubject(row.subject, row.title, row.pdf_url, "", row.number);
  if (granular && granular !== row.subject) {
    row.subject = granular;
    await p.query("UPDATE syllabus_chapters SET subject = $1 WHERE id = $2", [granular, row.id]).catch(() => {});
  }
  return row;
}

/** Subject exactly as stored in the database (no guessing from the title or chapter number). */
export function storedSubject(rawSubject) {
  return String(rawSubject || "").trim() || "General";
}

/** Subject of an ncert_chapters row: its subject column, else its book column when that holds a subject name (not a code like "iesc1"). */
export function ncertSubjectName(row) {
  const s = String(row?.subject || "").trim();
  if (s) return s;
  const b = String(row?.book || "").trim();
  return b && !/^[a-z]{3,5}\d{1,2}$/i.test(b) ? b : null;
}

const NCERT_STOP = new Set(["the", "and", "of", "in", "to", "a", "an", "how", "do", "our", "for", "with", "is", "are"]);
const ncertWords = (t) =>
  new Set(
    String(t || "")
      .toLowerCase()
      .replace(/^\s*(chapter|ch\.?)\s*\d+\s*[:.\-–—]?\s*/i, "")
      .replace(/[^a-z0-9]+/g, " ")
      .split(" ")
      .filter((w) => w.length > 1 && !NCERT_STOP.has(w))
  );

function ncertTitleScore(a, b) {
  const A = ncertWords(a), B = ncertWords(b);
  if (!A.size || !B.size) return 0;
  let hit = 0;
  for (const w of A) if (B.has(w)) hit++;
  const base = hit / Math.max(A.size, B.size);
  // "Cell" vs "Cell: The Building Block of Life": every word of the shorter title is in the longer one
  return hit === Math.min(A.size, B.size) ? Math.max(base, 0.6) : base;
}

/**
 * Best ncert_chapters row for a chapter TITLE (the title is trusted over the chapter number, which is what
 * went wrong before). Same class wins; a close tie between different links is treated as "no match".
 */
export async function findNcertChapterByTitle({ classLevel = null, title = "" } = {}) {
  const p = getPool();
  const { rows } = await p.query("SELECT id, class, number, title, pdf_url FROM ncert_chapters WHERE pdf_url IS NOT NULL");
  return pickNcertByTitle(rows, title, classLevel);
}

function pickFrom(rows, title) {
  let best = null, tie = false;
  for (const r of rows || []) {
    const score = ncertTitleScore(title, r.title);
    if (score < 0.6) continue;
    if (!best || score > best.score) { best = { ...r, score }; tie = false; }
    else if (score === best.score && r.pdf_url !== best.pdf_url) tie = true;
  }
  return best && !tie ? best : null;
}

/** Best ncert_chapters row for a title: rows of the student's class first, then any class. Null when nothing matches or two different links tie. */
export function pickNcertByTitle(rows, title, classLevel = null) {
  const same = classLevel != null ? (rows || []).filter((r) => Number(r.class) === Number(classLevel)) : null;
  return (same && pickFrom(same, title)) || pickFrom(rows, title);
}

/**
 * Re-link a student's saved chapters to ncert_chapters (by title): number, subject, pdf_url and ncert_id all come
 * from the DB row. Fixes chapters saved before this existed. Returns { relinked, unmatched: [titles] }.
 */
export async function relinkUserChapters(chatId) {
  return withDb(async (db) => {
    const { rows: ncert } = await db.query("SELECT id, class, book, subject, number, title, pdf_url FROM ncert_chapters WHERE pdf_url IS NOT NULL");
    const out = { relinked: 0, unmatched: [] };
    if (!ncert.length) return out;
    const { rows: chs } = await db.query(
      `SELECT sc.id, COALESCE(sc.class, ch.class, u.class_level) AS class, sc.subject, sc.exam, sc.number, sc.title, sc.pdf_url, sc.ncert_id
         FROM syllabus_chapters sc LEFT JOIN chats ch ON ch.chat_id = sc.chat_id
       LEFT JOIN users u ON u.telegram_user_id = sc.chat_id WHERE sc.chat_id = $1`,
      [chatId]
    );
    for (const c of chs) {
      const row = pickNcertByTitle(ncert, c.title, c.class);
      if (!row) { out.unmatched.push(c.title); continue; }
      const subject = ncertSubjectName(row) || c.subject;
      if (c.ncert_id === row.id && c.pdf_url === row.pdf_url && c.number === row.number && c.subject === subject) continue;
      await db.query("UPDATE syllabus_chapters SET ncert_id = $1, number = $2, pdf_url = $3, subject = $4, match_status = 'matched' WHERE id = $5", [row.id, row.number, row.pdf_url, subject, c.id]);
      if (subject !== c.subject) {
        // keep generation status and quiz results attached to the chapter under its new subject (savepoints: a clash must not abort the rest)
        for (const q of [
          ["UPDATE chapter_generation g SET subject = $1, chapter_number = $2 WHERE g.telegram_user_id = $3 AND g.subject = $4 AND g.exam = $5 AND lower(g.chapter_title) = lower($6) AND NOT EXISTS (SELECT 1 FROM chapter_generation x WHERE x.telegram_user_id = $3 AND x.subject = $1 AND x.exam = $5 AND lower(x.chapter_title) = lower($6))", [subject, row.number, chatId, c.subject, c.exam || "", c.title]],
          ["UPDATE chapter_quiz_results SET subject = $1 WHERE telegram_user_id = $2 AND subject = $3 AND exam = $4 AND chapter_title = $5", [subject, chatId, c.subject, c.exam || "", c.title]],
        ]) {
          await db.query("SAVEPOINT relink");
          try { await db.query(q[0], q[1]); await db.query("RELEASE SAVEPOINT relink"); }
          catch { await db.query("ROLLBACK TO SAVEPOINT relink"); }
        }
      }
      out.relinked++;
    }
    if (out.relinked || out.unmatched.length) {
      console.log(`[ncert] user ${chatId}: re-linked ${out.relinked} chapter(s) from ncert_chapters` + (out.unmatched.length ? `; no title match in ncert_chapters for: ${out.unmatched.join(" | ")}` : ""));
    }
    return out;
  });
}

/**
 * NCERT chapter PDF links stored in the ncert_chapters table, best first:
 * the row whose title matches the chapter (same class), then the row linked by ncert_id, then exact-title rows
 * from any class. Returns [] when nothing is stored: nothing is guessed or generated.
 */
export async function getNcertPdfUrls({ ncertId = null, classLevel = null, title = "" } = {}) {
  await initDb();
  const p = getPool();
  const urls = [];
  const byTitle = await findNcertChapterByTitle({ classLevel, title }).catch(() => null);
  if (byTitle?.pdf_url) urls.push(byTitle.pdf_url);
  if (ncertId != null) {
    const { rows } = await p.query("SELECT pdf_url FROM ncert_chapters WHERE id = $1", [ncertId]);
    for (const r of rows) if (r.pdf_url) urls.push(r.pdf_url);
  }
  const want = [...ncertWords(title)].join(" ");
  if (want) {
    const { rows } = await p.query(
      `SELECT pdf_url FROM ncert_chapters
        WHERE pdf_url IS NOT NULL
          AND btrim(regexp_replace(lower(title), '[^a-z0-9]+', ' ', 'g')) = $1
        ORDER BY (class = $2) DESC NULLS LAST, class, number`,
      [want, classLevel]
    );
    for (const r of rows) if (r.pdf_url) urls.push(r.pdf_url);
  }
  return [...new Set(urls)];
}

