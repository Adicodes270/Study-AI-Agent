// src/db.js  (Neon / Postgres)
import pg from "pg";

import { DATABASE_URL } from "./config.js";

// Telegram ids can be larger than int32, so the columns are BIGINT.
// node-postgres returns BIGINT as a string by default; ids fit safely in a JS number.
pg.types.setTypeParser(20, (v) => Number(v));

let pool = null;
function getPool() {
  if (!DATABASE_URL) {
    throw new Error("DATABASE_URL is not set. Add your Neon connection string to .env");
  }
  if (!pool) {
    pool = new pg.Pool({
      connectionString: DATABASE_URL,
      max: 5, // keep small: Neon (and serverless) limit connections
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
    });
    // An idle client can be dropped by Neon (autosuspend); don't crash the process
    pool.on("error", (err) => console.log(`Postgres pool error: ${err.message}`));
  }
  return pool;
}

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
    telegram_user_id     BIGINT PRIMARY KEY,
    gemini_api_key       TEXT NOT NULL,
    gemini_fallback_keys TEXT NOT NULL DEFAULT '[]',
    google_email         TEXT,
    notebooklm_state     TEXT,
    notebooklm_saved_at  TIMESTAMPTZ,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chats (
    chat_id BIGINT PRIMARY KEY,
    class   INTEGER
);

CREATE TABLE IF NOT EXISTS ncert_chapters (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class    INTEGER NOT NULL,
    book     TEXT NOT NULL,
    edition  TEXT NOT NULL,
    number   INTEGER NOT NULL,
    title    TEXT NOT NULL,
    pdf_url  TEXT,
    pdf_path TEXT
);

CREATE TABLE IF NOT EXISTS syllabus_chapters (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id      BIGINT NOT NULL REFERENCES chats(chat_id),
    class        INTEGER,
    subject      TEXT NOT NULL,
    exam         TEXT NOT NULL DEFAULT '',
    number       INTEGER,
    title        TEXT NOT NULL,
    note         TEXT,
    pdf_url      TEXT,
    ncert_id     INTEGER REFERENCES ncert_chapters(id),
    match_status TEXT NOT NULL DEFAULT 'pending'
);

CREATE INDEX IF NOT EXISTS idx_syllabus_lookup
    ON syllabus_chapters (chat_id, subject, exam);

-- "/start SA-1234" sent to the bot: lets the setup page learn the student's Telegram id without
-- the browser ever talking to Telegram (and so without the bot token leaving the server).
CREATE TABLE IF NOT EXISTS pairings (
    code       TEXT PRIMARY KEY,
    chat_id    BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    first_name TEXT,
    username   TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A quiz that has been generated but not yet submitted. Kept in the database (not in server memory)
-- so it survives restarts, redeploys and running more than one server instance. The answer key
-- lives in questions_json and never leaves the server until the quiz is submitted.
CREATE TABLE IF NOT EXISTS quiz_sessions (
    id               TEXT PRIMARY KEY,
    telegram_user_id BIGINT NOT NULL,
    chapter_json     TEXT NOT NULL,
    questions_json   TEXT NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Latest quiz result per student per chapter.
-- Not a foreign key to syllabus_chapters on purpose: saveSyllabus() deletes and re-inserts a
-- subject's rows whenever the syllabus changes, which would orphan (or cascade-delete) results.
-- A chapter is identified by (subject, exam, title) instead, which survives re-uploads.
CREATE TABLE IF NOT EXISTS chapter_quiz_results (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_user_id   BIGINT NOT NULL,
    chapter_id         INTEGER,
    subject            TEXT NOT NULL,
    exam               TEXT NOT NULL DEFAULT '',
    chapter_title      TEXT NOT NULL,
    score              INTEGER NOT NULL,
    total              INTEGER NOT NULL,
    percentage         INTEGER NOT NULL,
    revision_tier      TEXT NOT NULL,
    revision_message   TEXT NOT NULL,
    weak_subtopics_json TEXT NOT NULL DEFAULT '[]',
    attempts           INTEGER NOT NULL DEFAULT 1,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (telegram_user_id, subject, exam, chapter_title)
);
`;

// Runs once per process; concurrent callers share the same promise.
let schemaReady = null;

/** Create tables if they don't exist yet. Safe to call many times. */
export function initDb() {
  if (!schemaReady) {
    schemaReady = getPool()
      .query(SCHEMA)
      .then(() => undefined)
      .catch((err) => {
        schemaReady = null; // allow a retry on the next call
        throw err;
      });
  }
  return schemaReady;
}

/**
 * Run `fn(db)` inside a transaction. `db.query(sql, params)` is the usual
 * node-postgres client query (use $1, $2, ... placeholders; rows are in `.rows`).
 * Commits if everything worked, rolls back if anything threw.
 */
export async function withDb(fn) {
  await initDb();
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

/** Close the pool (for scripts and clean shutdown). */
export async function closeDb() {
  if (pool) {
    await pool.end();
    pool = null;
    schemaReady = null;
  }
}

