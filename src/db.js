const TOOL_RESULT_MAX_BYTES = 2048;

/**
 * Truncate `tool_result` payloads to ~2KB (2048 bytes) while preserving valid JSONB structure.
 */
export function truncateToolResult(toolResult, maxBytes = TOOL_RESULT_MAX_BYTES) {
  if (toolResult === undefined || toolResult === null) return null;
  try {
    const rawStr = typeof toolResult === "string" ? toolResult : JSON.stringify(toolResult);
    if (typeof rawStr !== "string") return null;
    const byteLen = Buffer.byteLength(rawStr, "utf8");
    if (byteLen <= maxBytes) {
      if (typeof toolResult === "string") {
        try {
          return JSON.parse(toolResult);
        } catch {
          return toolResult;
        }
      }
      return toolResult;
    }
    const previewBudget = Math.max(256, maxBytes - 120);
    const preview = Buffer.from(rawStr, "utf8").subarray(0, previewBudget).toString("utf8");
    return {
      _truncated: true,
      original_bytes: byteLen,
      preview: `${preview}...[truncated]`,
    };
  } catch {
    const fallback = String(toolResult).slice(0, Math.max(256, maxBytes - 120));
    return {
      _truncated: true,
      preview: `${fallback}...[truncated]`,
    };
  }
}

function nextLocalRowId(list) {
  if (!Array.isArray(list) || !list.length) return 1;
  let max = 0;
  for (const item of list) {
    const n = Number(item?.id);
    if (Number.isFinite(n) && n > max) max = n;
  }
  return max + 1;
}

function normalizeJsonValue(val, fallback = {}) {
  if (val === undefined) return fallback;
  if (val === null) return null;
  if (typeof val === "string") {
    try {
      return JSON.parse(val);
    } catch {
      return val;
    }
  }
  return val;
}

function formatAgentActionRow(r) {
  if (!r) return null;
  return {
    id: Number(r.id),
    telegram_user_id: Number(r.telegram_user_id ?? r.telegramUserId ?? r.userId),
    tick_type: String(r.tick_type ?? r.tickType ?? "event"),
    tool_name: r.tool_name ?? r.toolName ?? null,
    tool_args: normalizeJsonValue(r.tool_args ?? r.toolArgs, {}),
    tool_result: normalizeJsonValue(r.tool_result ?? r.toolResult, null),
    message_sent: r.message_sent ?? r.messageSent ?? null,
    reasoning: r.reasoning ?? null,
    status: String(r.status || "ok"),
    created_at: r.created_at instanceof Date ? r.created_at.toISOString() : String(r.created_at || new Date().toISOString()),
  };
}

/**
 * Log an agent action row to `agent_actions` (and local fallback store), truncating `tool_result` to ~2KB.
 */
export async function logAgentAction(row = {}) {
  const telegramUserId = Number(row.telegram_user_id ?? row.telegramUserId ?? row.userId ?? 0);
  const tickType = String(row.tick_type ?? row.tickType ?? "event");
  const toolName = row.tool_name ?? row.toolName ?? null;
  const toolArgs = normalizeJsonValue(row.tool_args ?? row.toolArgs, {});
  const rawToolResult = row.tool_result !== undefined ? row.tool_result : row.toolResult;
  const toolResult = truncateToolResult(rawToolResult);
  const messageSent = row.message_sent ?? row.messageSent ?? null;
  const reasoning = row.reasoning ?? null;
  const status = String(row.status || "ok");
  const createdAt =
    row.created_at || row.createdAt
      ? new Date(row.created_at ?? row.createdAt).toISOString()
      : new Date().toISOString();

  const store = readLocalStore();
  store.agentActions = Array.isArray(store.agentActions) ? store.agentActions : [];
  const localEntry = {
    id: nextLocalRowId(store.agentActions),
    telegram_user_id: telegramUserId,
    tick_type: tickType,
    tool_name: toolName,
    tool_args: toolArgs,
    tool_result: toolResult,
    message_sent: messageSent,
    reasoning,
    status,
    created_at: createdAt,
  };
  store.agentActions.push(localEntry);
  writeLocalStore(store);

  if (hasDatabaseUrl()) {
    try {
      await initDb();
      const { rows } = await getPool().query(
        `INSERT INTO agent_actions
           (telegram_user_id, tick_type, tool_name, tool_args, tool_result, message_sent, reasoning, status, created_at)
         VALUES ($1, $2, $3, $4::jsonb, $5::jsonb, $6, $7, $8, $9::timestamptz)
         RETURNING id, telegram_user_id, tick_type, tool_name, tool_args, tool_result, message_sent, reasoning, status, created_at`,
        [
          telegramUserId,
          tickType,
          toolName,
          toolArgs === null ? null : JSON.stringify(toolArgs),
          toolResult === null ? null : JSON.stringify(toolResult),
          messageSent,
          reasoning,
          status,
          createdAt,
        ]
      );
      if (rows[0]) {
        const dbRow = formatAgentActionRow(rows[0]);
        localEntry.id = dbRow.id;
        localEntry.created_at = dbRow.created_at;
        writeLocalStore(store);
        return dbRow;
      }
    } catch (e) {
      console.log(`Could not log agent action to Postgres (saved locally): ${e.message}`);
    }
  }

  return formatAgentActionRow(localEntry);
}

/**
 * Fetch the most recent `agent_actions` rows for a user, ordered newest first.
 */
export async function getRecentAgentActions(userId, limit = 20) {
  const uid = Number(userId);
  const lim = Math.max(1, Math.min(500, parseInt(limit, 10) || 20));

  if (hasDatabaseUrl()) {
    try {
      await initDb();
      const { rows } = await getPool().query(
        `SELECT id, telegram_user_id, tick_type, tool_name, tool_args, tool_result, message_sent, reasoning, status, created_at
           FROM agent_actions
          WHERE telegram_user_id = $1
          ORDER BY created_at DESC, id DESC
          LIMIT $2`,
        [uid, lim]
      );
      if (rows.length) {
        return rows.map(formatAgentActionRow);
      }
    } catch {}
  }

  const store = readLocalStore();
  const list = Array.isArray(store.agentActions) ? store.agentActions : [];
  return list
    .filter((r) => Number(r.telegram_user_id) === uid)
    .sort((a, b) => {
      const diff = new Date(b.created_at).getTime() - new Date(a.created_at).getTime();
      return diff !== 0 ? diff : Number(b.id) - Number(a.id);
    })
    .slice(0, lim)
    .map(formatAgentActionRow);
}

